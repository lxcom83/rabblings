# Builds games/rabblings/foe-art.js from the procedural sample art (tools/foe_samples.py).
import base64,io,sys,importlib.util
from PIL import Image
spec=importlib.util.spec_from_file_location('foe_samples','tools/foe_samples.py');M=importlib.util.module_from_spec(spec);spec.loader.exec_module(M)
INK=(9,10,12,255)
def crop(im):
    return im.crop(im.getbbox())
def fit(im,w):
    im=crop(im);h=max(1,round(im.height*w/im.width))
    return im.resize((w,h),Image.NEAREST)
def outline(im):
    o=Image.new('RGBA',(im.width+2,im.height+2),(0,0,0,0));a=im.split()[3];px=o.load();src=im.load()
    for y in range(im.height):
        for x in range(im.width):
            if a.getpixel((x,y))>0:
                for dx,dy in((0,1),(1,0),(1,1),(1,2),(2,1),(0,1),(1,0)):
                    if px[x+dx,y+dy][3]==0:px[x+dx,y+dy]=INK
    for y in range(im.height):
        for x in range(im.width):
            if src[x,y][3]>0:px[x+1,y+1]=src[x,y]
    return o
def b64(im):
    b=io.BytesIO();im.save(b,'PNG',optimize=True);return base64.b64encode(b.getvalue()).decode()
S={'skel':[fit(M.stalker(),46),fit(M.stalker_pounce(),46)],'spider':[fit(M.spider(),40)],'golem':[fit(M.brute(),34)],
   'rat':[crop(M.gutter(0)),crop(M.gutter(1))],'arch':[crop(M.raider(0)),crop(M.raider(1))],'raptor':[fit(M.raptor(),44)],'lurker':[fit(M.lurker(),44),fit(M.lurker_water(),44)]}
out='// generated by tools/gen_foe_art.py: Lore creatures at game size\nconst FOESPR=(function(){const S={};const mk=(k,l)=>{S[k]=l.map(u=>{const i=new Image();i.src="data:image/png;base64,"+u;return i;});};\n'
for k,v in S.items():
    out+='mk(%r,[%s]);\n'%(k,','.join('"'+b64(outline(i))+'"' for i in v))
    print(k,[(i.width+2,i.height+2) for i in v])
out+='return S;})();\n'
open('games/rabblings/foe-art.js','w').write(out)
